import widths from '../data/images.json'

/*
  Responsive photo props: <img {...img('/images/station.webp', '50vw')} />
  Adds the srcset generated by scripts/images.py so phones get the 640/1080px files instead of the
  full desktop photo. `sizes` should describe how wide the image is shown (CSS lengths / media queries).
*/
// On 3× phone screens a photo at 2× density looks identical — ask for ~2/3 of the width instead
export const PHONE_DPR_CAP = '(max-width: 767px) and (min-resolution: 2.5dppx) 67vw'

export function img(src, sizes = '100vw') {
  const name = src.match(/\/images\/([^/]+)\.webp$/)?.[1]
  const set = name && widths[name]
  if (!set) return { src }
  if (/(^|, )100vw$/.test(sizes)) sizes = `${PHONE_DPR_CAP}, ${sizes}`
  const srcSet = set.map((w, i) => `${i === set.length - 1 ? src : src.replace(/\.webp$/, `-${w}.webp`)} ${w}w`).join(', ')
  return { src, srcSet, sizes }
}
